CREATE TABLE rental_agreements
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT         NOT NULL REFERENCES users (id),
    unit_id    BIGINT         NOT NULL REFERENCES equipment_units (id),
    start_date TIMESTAMP      NOT NULL,
    end_date   TIMESTAMP      NOT NULL,
    status     VARCHAR(20)    NOT NULL CHECK (status IN ('RESERVED', 'ACTIVE', 'OVERDUE', 'RETURNED', 'SETTLED', 'CANCELLED')),
    base_price NUMERIC(10, 2) NOT NULL CHECK (base_price >= 0),
    deposit    NUMERIC(10, 2) NOT NULL CHECK (deposit >= 0),
    created_at TIMESTAMP      NOT NULL DEFAULT now(),
    version    BIGINT         NOT NULL DEFAULT 0,
    CHECK (end_date > start_date)
);

-- Pod zapytanie o kolizję terminów (R1)
CREATE INDEX idx_agreements_unit_dates ON rental_agreements (unit_id, start_date, end_date);
CREATE INDEX idx_agreements_client ON rental_agreements (client_id);
