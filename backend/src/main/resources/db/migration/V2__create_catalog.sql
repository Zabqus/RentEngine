CREATE TABLE categories
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL UNIQUE,
    type            VARCHAR(20)  NOT NULL CHECK (type IN ('CAR', 'EXCAVATOR', 'MOWER', 'TRACTOR', 'CONSTRUCTION')),
    required_params JSONB        NOT NULL DEFAULT '[]'
);

CREATE TABLE equipment
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255)   NOT NULL,
    category_id   BIGINT         NOT NULL REFERENCES categories (id),
    daily_price   NUMERIC(10, 2) NOT NULL CHECK (daily_price > 0),
    deposit       NUMERIC(10, 2) NOT NULL CHECK (deposit >= 0),
    tank_capacity NUMERIC(6, 2) CHECK (tank_capacity > 0),
    params        JSONB          NOT NULL DEFAULT '{}'
);

CREATE INDEX idx_equipment_category ON equipment (category_id);

CREATE TABLE equipment_units
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id     BIGINT       NOT NULL REFERENCES equipment (id),
    serial_or_plate  VARCHAR(50)  NOT NULL UNIQUE,
    status           VARCHAR(20)  NOT NULL CHECK (status IN ('AVAILABLE', 'IN_SERVICE')),
    mileage_or_hours INTEGER      NOT NULL DEFAULT 0 CHECK (mileage_or_hours >= 0),
    version          BIGINT       NOT NULL DEFAULT 0
);

CREATE INDEX idx_units_equipment ON equipment_units (equipment_id);
