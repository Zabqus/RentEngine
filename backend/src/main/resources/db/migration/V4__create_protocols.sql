CREATE TABLE protocols
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agreement_id     BIGINT      NOT NULL REFERENCES rental_agreements (id),
    type             VARCHAR(10) NOT NULL CHECK (type IN ('ISSUE', 'RETURN')),
    fuel_level       NUMERIC(6, 2) CHECK (fuel_level >= 0),
    mileage_or_hours INTEGER     NOT NULL CHECK (mileage_or_hours >= 0),
    notes            TEXT,
    employee_id      BIGINT      NOT NULL REFERENCES users (id),
    created_at       TIMESTAMP   NOT NULL DEFAULT now(),
    -- Jedna umowa ma maksymalnie jeden protokół wydania i jeden zwrotu
    UNIQUE (agreement_id, type)
);

CREATE TABLE damages
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocol_id BIGINT         NOT NULL REFERENCES protocols (id) ON DELETE CASCADE,
    description VARCHAR(500)   NOT NULL,
    severity    VARCHAR(10)    NOT NULL CHECK (severity IN ('MINOR', 'MAJOR')),
    cost        NUMERIC(10, 2) NOT NULL CHECK (cost >= 0),
    photo_path  VARCHAR(500)
);

CREATE INDEX idx_damages_protocol ON damages (protocol_id);
